"""System error analysis for NyayaSetu legal retrieval baselines.

Performs deterministic diagnostic classification for failed or degraded queries
where rank > 1, rank > 5, or target evidence is missed.

NOTE ON ANNOTATION AUTHORITY:
All categories generated by this module are classified heuristically under
SYSTEM_ERROR_ANALYSIS. They reflect computational failure diagnoses and must NOT
be represented as human legal expert ground truth annotations.
"""

import argparse
import json
from dataclasses import asdict, dataclass
from enum import Enum
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple


class FailureCategory(str, Enum):
    """Failure categories for legal retrieval diagnosis."""

    LEXICAL_MISMATCH = "LEXICAL_MISMATCH"
    SEMANTIC_MISMATCH = "SEMANTIC_MISMATCH"
    STATUTE_CONFUSION = "STATUTE_CONFUSION"
    SECTION_CONFUSION = "SECTION_CONFUSION"
    QUERY_AMBIGUITY = "QUERY_AMBIGUITY"
    MISSING_CORPUS_EVIDENCE = "MISSING_CORPUS_EVIDENCE"
    INDEXING_FAILURE = "INDEXING_FAILURE"
    ROUTING_CORRECT_RETRIEVAL_FAILURE = "ROUTING_CORRECT_RETRIEVAL_FAILURE"
    ROUTING_INCORRECT = "ROUTING_INCORRECT"
    HIGH_CONFIDENCE_ROUTING_ERROR = "HIGH_CONFIDENCE_ROUTING_ERROR"
    MULTI_REGIME_MISROUTING = "MULTI_REGIME_MISROUTING"
    FALLBACK_REQUIRED = "FALLBACK_REQUIRED"
    CROSS_STATUTE_CONFUSION_REDUCED = "CROSS_STATUTE_CONFUSION_REDUCED"
    UNKNOWN = "UNKNOWN"


@dataclass
class QueryErrorRecord:
    """Standard record for a retrieval failure or rank degradation."""

    query_id: str
    question: str
    expected_target: str
    retrieved_top_5: List[str]
    rank_of_first_relevant_result: Optional[int]
    baseline_configuration: str
    failure_category: str
    notes: str
    analysis_type: str = "SYSTEM_ERROR_ANALYSIS"
    routing_mode: Optional[str] = None
    routing_selected_regimes: Optional[List[str]] = None
    routing_fallback_used: Optional[bool] = None

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


def is_statute_match(retrieved_doc: str, expected_target: str) -> bool:
    """Check if retrieved document title matches expected statutory enactment."""
    if not retrieved_doc or not expected_target:
        return False
    rd = retrieved_doc.lower().strip()
    et = expected_target.lower().strip()
    return et in rd or rd in et


def classify_retrieval_failure(
    query_id: str,
    question: str,
    expected_target: str,
    retrieved_docs: List[str],
    rank: Optional[int],
    is_ambiguous: bool = False,
    is_out_of_scope: bool = False,
    corpus_known_docs: Optional[Sequence_str] = None,
    routing_mode: Optional[str] = None,
    routing_selected_regimes: Optional[List[str]] = None,
    routing_fallback_used: Optional[bool] = None,
) -> Tuple[FailureCategory, str]:
    """Heuristically determine failure category under SYSTEM_ERROR_ANALYSIS."""
    q_lower = question.lower()
    exp_lower = expected_target.lower() if expected_target else ""

    # 1. Ambiguity or out of scope
    if is_ambiguous or "ambiguous" in query_id.lower():
        return (
            FailureCategory.QUERY_AMBIGUITY,
            "Query phrasing lacks necessary material facts to uniquely resolve governing enactment.",
        )

    if is_out_of_scope or "out_of_scope" in query_id.lower() or not expected_target:
        return (
            FailureCategory.QUERY_AMBIGUITY,
            "Query seeks out-of-scope, non-Indian, or non-statutory advice with null target document.",
        )

    # 2. Missing corpus evidence check
    if corpus_known_docs and not any(exp_lower in kd.lower() for kd in corpus_known_docs):
        return (
            FailureCategory.MISSING_CORPUS_EVIDENCE,
            f"Target document '{expected_target}' does not exist in indexed statutory collection.",
        )

    # 3. Routing-informed diagnostics if routing metadata is present
    if routing_mode and routing_selected_regimes:
        # Determine expected regime ID from expected_target
        target_regime_map = {
            "bns": "BNS_SUBSTANTIVE",
            "bharatiya nyaya sanhita": "BNS_SUBSTANTIVE",
            "bnss": "BNSS_PROCEDURAL",
            "bharatiya nagarik suraksha": "BNSS_PROCEDURAL",
            "bsa": "BSA_EVIDENCE",
            "bharatiya sakshya": "BSA_EVIDENCE",
            "it act": "IT_ACT",
            "information technology": "IT_ACT",
            "constitution": "CONSTITUTION",
            "consumer": "CONSUMER_PROTECTION",
            "motor": "MOTOR_VEHICLES",
            "pocso": "POCSO_CHILD",
            "posh": "POSH_LABOUR",
        }
        exp_regime = None
        for k, v in target_regime_map.items():
            if k in exp_lower:
                exp_regime = v
                break

        if routing_fallback_used:
            return (
                FailureCategory.FALLBACK_REQUIRED,
                f"Fact router triggered uncertainty fallback; retrieval operated over unrouted global index (Rank={rank}).",
            )

        if exp_regime:
            if exp_regime in routing_selected_regimes:
                # Routing was correct, but retrieval failed or was degraded
                return (
                    FailureCategory.ROUTING_CORRECT_RETRIEVAL_FAILURE,
                    f"Fact router correctly selected regime '{exp_regime}', but chunk-level retrieval ranked target at {rank}.",
                )
            else:
                if routing_mode == "high_confidence":
                    return (
                        FailureCategory.HIGH_CONFIDENCE_ROUTING_ERROR,
                        f"CRITICAL: Router had high confidence in {routing_selected_regimes} but ground truth requires '{exp_regime}'.",
                    )
                else:
                    return (
                        FailureCategory.ROUTING_INCORRECT,
                        f"Router selected {routing_selected_regimes} while ground truth required '{exp_regime}'.",
                    )

    # 4. Complete miss (not in top 5)
    if rank is None or rank < 1 or rank > 5:
        # Check if retrieved docs are from other statutes entirely
        if retrieved_docs and not any(is_statute_match(rd, expected_target) for rd in retrieved_docs[:5]):
            statute_keywords = ["bns", "sanhita", "ipc", "crpc", "constitution", "pocso", "it act", "information technology"]
            if any(sk in q_lower for sk in statute_keywords):
                return (
                    FailureCategory.STATUTE_CONFUSION,
                    f"Retriever retrieved unrelated enactments ({retrieved_docs[:2]}) despite query referencing {expected_target}.",
                )
            else:
                return (
                    FailureCategory.SEMANTIC_MISMATCH,
                    f"Semantic vector failed to link natural language query to {expected_target}; retrieved {retrieved_docs[:2]}.",
                )
        else:
            return (
                FailureCategory.LEXICAL_MISMATCH,
                f"Target enactment present in candidates but pushed outside top-5 by non-salient matches.",
            )

    # 5. Ranked between 2 and 5 (degraded rank: Hit@5=1.0 but Hit@1=0.0)
    top_1_doc = retrieved_docs[0] if retrieved_docs else ""
    if not is_statute_match(top_1_doc, expected_target):
        if any(term in q_lower for term in ["section", "article", "punishment", "definition"]):
            return (
                FailureCategory.SECTION_CONFUSION,
                f"Correct statute retrieved at rank {rank}, but rank 1 displaced by {top_1_doc}.",
            )
        else:
            return (
                FailureCategory.SEMANTIC_MISMATCH,
                f"Cross-statutory semantic overlap allowed {top_1_doc} to score higher than expected {expected_target} at rank 1.",
            )
    else:
        return (
            FailureCategory.UNKNOWN,
            f"Statute matched at rank {rank}; degradation may involve internal section-level sub-ranking.",
        )


Sequence_str = Sequence = List[str]


def analyze_experiment_errors(
    predictions: List[Dict[str, Any]],
    baseline_name: str,
    target_rank: int = 1,
) -> List[QueryErrorRecord]:
    """Identify and classify all degraded or failed queries in an experiment.

    A query is considered degraded if its reciprocal rank is < 1.0 (i.e. first relevant hit > target_rank).
    """
    error_records: List[QueryErrorRecord] = []

    for item in predictions:
        qid = item.get("query_id", "")
        qtext = item.get("question", "")
        exp_doc = item.get("expected_document", "")
        is_neg = item.get("is_negative_or_out_of_scope", False)
        ret_docs = item.get("retrieved_documents", [])
        rr = float(item.get("reciprocal_rank", 0.0))
        r_mode = item.get("routing_mode")
        r_regs = item.get("routing_selected_regimes")
        r_fb = item.get("routing_fallback_used")

        # Skip non-evaluable queries if looking for statutory retrieval failure
        if not exp_doc or str(exp_doc).lower() == "none" or is_neg:
            continue

        rank_of_first: Optional[int] = None
        if rr > 0.0:
            rank_of_first = int(round(1.0 / rr))

        # Check failure or degradation
        if rank_of_first is None or rank_of_first > target_rank:
            cat, notes = classify_retrieval_failure(
                query_id=qid,
                question=qtext,
                expected_target=exp_doc,
                retrieved_docs=ret_docs,
                rank=rank_of_first,
                is_ambiguous=False,
                is_out_of_scope=is_neg,
                routing_mode=r_mode,
                routing_selected_regimes=r_regs,
                routing_fallback_used=r_fb,
            )

            record = QueryErrorRecord(
                query_id=qid,
                question=qtext,
                expected_target=exp_doc,
                retrieved_top_5=ret_docs[:5],
                rank_of_first_relevant_result=rank_of_first,
                baseline_configuration=baseline_name,
                failure_category=cat.value,
                notes=notes,
                analysis_type="SYSTEM_ERROR_ANALYSIS",
                routing_mode=r_mode,
                routing_selected_regimes=r_regs,
                routing_fallback_used=r_fb,
            )
            error_records.append(record)

    return error_records

    return error_records


def summarize_failure_categories(records: List[QueryErrorRecord]) -> Dict[str, int]:
    """Count occurrences of each failure category."""
    counts: Dict[str, int] = {}
    for r in records:
        counts[r.failure_category] = counts.get(r.failure_category, 0) + 1
    return counts


def main():
    parser = argparse.ArgumentParser(description="Perform system error analysis on predictions.")
    parser.add_argument("--predictions", required=True, help="Path to predictions.jsonl")
    parser.add_argument("--baseline_name", default="baseline", help="Baseline name")
    parser.add_argument("--output_json", default=None, help="Output JSON path")
    args = parser.parse_args()

    pred_path = Path(args.predictions)
    with open(pred_path, "r", encoding="utf-8") as f:
        predictions = [json.loads(line) for line in f if line.strip()]

    errors = analyze_experiment_errors(predictions, args.baseline_name)
    counts = summarize_failure_categories(errors)

    print("\n" + "=" * 80)
    print(f"SYSTEM_ERROR_ANALYSIS: {args.baseline_name} (Degraded / Failed Queries: {len(errors)})")
    print("=" * 80)
    for cat, cnt in sorted(counts.items(), key=lambda x: x[1], reverse=True):
        print(f"  {cat:<25}: {cnt}")
    print("=" * 80)

    if args.output_json:
        out_path = Path(args.output_json)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        with open(out_path, "w", encoding="utf-8") as f:
            json.dump([e.to_dict() for e in errors], f, indent=2)
        print(f"Detailed error records written to {out_path}")


if __name__ == "__main__":
    main()
