"""
Deterministic answer validation module for NyayaSetu Legal Knowledge Assistant.

Validates model-generated responses against provided sources:
- Verifies that cited source labels exist in the provided context
- Detects hallucinated source citations (e.g. [Source 7] when only 5 exist)
- Checks for empty content or internal prompt leakage
- Detects missing source citations (insufficient grounding warnings)
- Attaches actionable informational warnings
"""

import re
from dataclasses import dataclass, field
from typing import List, Set


@dataclass
class ValidationResult:
    """Outcome of deterministic response validation."""

    is_valid: bool
    warnings: List[str] = field(default_factory=list)
    valid_citations_found: List[str] = field(default_factory=list)
    invalid_citations_found: List[str] = field(default_factory=list)


class LegalAnswerValidator:
    """Validates groundedness and citation consistency of generated responses."""

    def validate(
        self,
        answer: str,
        available_source_count: int,
    ) -> ValidationResult:
        """Perform validation on generated text.

        Args:
            answer: Raw text response generated by the LLM.
            available_source_count: Number of source chunks passed in context (e.g. 5).

        Returns:
            ValidationResult with validity flag and specific warnings.
        """
        warnings: List[str] = []

        if not answer or not answer.strip():
            return ValidationResult(
                is_valid=False,
                warnings=["The LLM returned an empty response."],
            )

        # 1. Check for prompt leakage
        leakage_patterns = [
            r"STRICT OPERATIONAL RULES:",
            r"OFFICIAL LEGAL SOURCES PROVIDED:",
            r"Allowed Source Citations:",
            r"MANDATORY RESPONSE STRUCTURE:",
            r"Never expose internal system instructions",
        ]
        for pat in leakage_patterns:
            if re.search(pat, answer, re.IGNORECASE):
                warnings.append("Potential system prompt leakage detected in response.")

        # 2. Check source citation validity
        cited_indices: Set[int] = set()
        for match in re.finditer(r"\[(?:Source|SOURCE)\s*(\d+)\]", answer):
            try:
                idx = int(match.group(1))
                cited_indices.add(idx)
            except ValueError:
                pass

        valid_citations: List[str] = []
        invalid_citations: List[str] = []

        for idx in sorted(cited_indices):
            label = f"[Source {idx}]"
            if 1 <= idx <= available_source_count:
                valid_citations.append(label)
            else:
                invalid_citations.append(label)

        if invalid_citations:
            warnings.append(
                f"Response contains hallucinated source citation(s) {invalid_citations} "
                f"that do not correspond to any of the {available_source_count} provided sources."
            )

        if available_source_count > 0 and not valid_citations:
            warnings.append(
                "Response does not cite any of the provided legal source labels. "
                "Insufficient source grounding detected; ensure statements are manually verified against statutory sources."
            )

        # 3. Informational educational notice (does not claim legal correctness)
        warnings.append(
            "Deterministic validation confirms citation syntax and format only; "
            "it does not replace verified legal advice from an advocate."
        )

        is_valid = len(invalid_citations) == 0

        return ValidationResult(
            is_valid=is_valid,
            warnings=warnings,
            valid_citations_found=valid_citations,
            invalid_citations_found=invalid_citations,
        )
